local map = vim.keymap.set

-- Líder: espacio
vim.g.mapleader = " "

-- Moverse entre ventanas sin Ctrl-W
map("n", "<C-h>", "<C-w>h")
map("n", "<C-j>", "<C-w>j")
map("n", "<C-k>", "<C-w>k")
map("n", "<C-l>", "<C-w>l")

-- Mover líneas en visual mode
map("v", "J", ":m '>+1<CR>gv=gv")
map("v", "K", ":m '<-2<CR>gv=gv")

-- Centrar la pantalla al saltar
map("n", "<C-d>", "<C-d>zz")
map("n", "<C-u>", "<C-u>zz")
map("n", "n", "nzzzv")
map("n", "N", "Nzzzv")

-- Pegar sin perder el registro
map("x", "<leader>p", '"_dP')
